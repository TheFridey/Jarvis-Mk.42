import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

/**
 * Local-development LiveKit configuration.
 *
 * A single explicit operator command generates the key pair, the server config and an env
 * file. Nothing here runs at startup, nothing is printed, nothing overwrites an existing
 * file, and nothing is written inside tracked source.
 */

export interface LivekitCredentials {
  apiKey: string;
  apiSecret: string;
}

/** LiveKit keys are conventionally `API` + 8–12 alphanumerics; the secret is 32+ bytes. */
export function newLivekitCredentials(): LivekitCredentials {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
  const bytes = randomBytes(12);
  let suffix = '';
  for (const byte of bytes) suffix += alphabet[byte % alphabet.length];
  return { apiKey: `API${suffix}`, apiSecret: randomBytes(32).toString('base64url') };
}

/** The server config mounted read-only into the container. Loopback only. */
export function renderLivekitYaml(credentials: LivekitCredentials): string {
  return [
    '# Local development only. Generated by scripts/rtc-config.mjs; do not commit.',
    'port: 7880',
    'bind_addresses:',
    '  - 127.0.0.1',
    'rtc:',
    '  tcp_port: 7881',
    '  udp_port: 7882',
    '  use_external_ip: false',
    '  enable_loopback_candidate: true',
    'keys:',
    `  ${credentials.apiKey}: ${credentials.apiSecret}`,
    'logging:',
    '  level: info',
    '  json: false',
    '',
  ].join('\n');
}

/** The env file the launcher sources; the Kernel reads these three names. */
export function renderEnvFile(credentials: LivekitCredentials): string {
  return [
    '# Local development only. Sourced by scripts/jarvis-up.ps1; never committed.',
    'JARVIS_LIVEKIT_URL=ws://127.0.0.1:7880',
    `JARVIS_LIVEKIT_API_KEY=${credentials.apiKey}`,
    `JARVIS_LIVEKIT_API_SECRET=${credentials.apiSecret}`,
    '',
  ].join('\n');
}

export interface WriteResult {
  written: string[];
  skipped: string[];
}

/**
 * Write the two files, refusing to touch anything that already exists. Secrets are never
 * returned to the caller for printing — only the paths are.
 */
export function writeLivekitConfig(options: {
  yamlPath: string;
  envPath: string;
  credentials?: LivekitCredentials;
  /** Restrict the ACLs after writing; omitted on non-Windows hosts. */
  restrict?: (path: string) => void;
}): WriteResult {
  const credentials = options.credentials ?? newLivekitCredentials();
  const result: WriteResult = { written: [], skipped: [] };

  const targets: Array<[string, string]> = [
    [options.yamlPath, renderLivekitYaml(credentials)],
    [options.envPath, renderEnvFile(credentials)],
  ];

  // Refuse before writing anything, so a half-generated pair cannot be left behind.
  for (const [path] of targets) if (existsSync(path)) throw new Error(`${path} already exists; refusing to overwrite`);
  if (!credentials.apiKey || credentials.apiSecret.length < 32) throw new Error('generated credentials are too weak');

  for (const [path, content] of targets) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content, { encoding: 'utf8', mode: 0o600, flag: 'wx' });
    try { chmodSync(path, 0o600); } catch { /* Windows: ACLs are applied below */ }
    options.restrict?.(path);
    result.written.push(path);
  }
  return result;
}
